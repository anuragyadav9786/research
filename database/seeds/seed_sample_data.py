"""Phase 2 seed data — a small, fully synthetic set of sample funds.

IMPORTANT — READ BEFORE TOUCHING THIS FILE
============================================
Every AMC, fund family, scheme, security, manager, NAV value and holding
weight in this file is FICTIONAL. None of it comes from AMFI, SEBI, NSE, RBI
or any AMC. It exists only to exercise the database schema end to end during
development (Rule 2: never fabricate real financial data; if real data is
unavailable, use clearly labelled mock data and never mix it with production
data).

How that rule is enforced here, concretely:
- AMC/fund-family/scheme names are invented ("Northbridge", "Meridian") —
  they do not resemble any real AMC or scheme name.
- All identifiers (AMFI codes, ISINs) are prefixed "SAMPLE-" so they can
  never collide with, or be mistaken for, a real identifier ingested later
  by the Phase 3 pipeline.
- The single `data_sources` row this script creates is named and typed
  accordingly ("manual" / "Synthetic Sample Data Generator"), so every NAV,
  benchmark and holdings row traces back to a source that says exactly what
  it is.
- NAV and benchmark histories are generated by a seeded random walk
  (`numpy.random.default_rng(SEED)`), not copied from any real fund or
  index — this is simulation, not data entry.

This script is idempotent: it checks for its own sample AMCs before
inserting anything, so re-running it is a no-op unless --reset is passed.
Once Phase 3 (real NAV ingestion) exists, this sample data must never be
presented to a user as if it were real; do not point production ingestion
runs at the same rows without first clearing this seed set.

Usage:
    cd backend && source .venv/bin/activate
    python ../database/seeds/seed_sample_data.py [--reset]
"""
